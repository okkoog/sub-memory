#!/usr/bin/env python3
import os, re, pathlib, json
ROOT = pathlib.Path(os.environ["DECOMPILED_ROOT"])
OUT = pathlib.Path("probably-stolen/analysis/localization-path-audit.md")
TARGETS = {
 "3832048841": ("game_card_pk","GameCardPK"),
 "3831837821": ("lewd_meme","MidnightPawn"),
 "3829429358": ("xiaowo_night_auction","XIAOWONightAuction"),
 "3829085054": ("Dream_Item_Storage","ItemStorage"),
 "3829730904": ("brewing_expansion","BrewingExpansion"),
}
CJK = re.compile(r"[\u3400-\u9fff]")
STR = re.compile(r'"((?:\\.|[^"\\])*)"')
ASSIGN_HINTS = ("name","desc","description","tooltip","title","subtitle","text","display","label","hover","localized","localization")
LOC_HINTS = ("GetLocalized","Localization","LoadLocalization","LocalizedString","LocHelper")
def method_of(lines, idx):
    for j in range(idx, max(-1, idx-40), -1):
        s=lines[j].strip()
        if ("(" in s and ")" in s and (" public " in " "+s or " private " in " "+s or " internal " in " "+s or " protected " in " "+s)) or s.startswith(("public ","private ","internal ","protected ")):
            return s[:220]
    return "(unknown method)"
def interesting_string(s):
    try:
        s=bytes(s,"utf-8").decode("unicode_escape")
    except Exception:
        pass
    if len(s.strip()) < 2: return False
    if CJK.search(s): return True
    # English UI-ish strings, not identifiers/paths.
    if len(s) >= 6 and " " in s and re.search(r"[A-Za-z]",s) and not re.search(r"[/\\]|\.png|\.json|\.xml|\.dll",s,re.I):
        return True
    return False
rows=[]
for wid,(modid,asm) in TARGETS.items():
    base=ROOT/wid
    files=list(base.rglob("*.cs"))
    modrows=[]
    loc_calls=0
    for p in files:
        try: lines=p.read_text(encoding="utf-8",errors="ignore").splitlines()
        except Exception: continue
        for i,line in enumerate(lines):
            if any(h in line for h in LOC_HINTS): loc_calls += 1
            for m in STR.finditer(line):
                raw=m.group(1)
                if not interesting_string(raw): continue
                ctx=" ".join(lines[max(0,i-2):min(len(lines),i+3)])
                kind="direct/display assignment" if any(h.lower() in ctx.lower() for h in ASSIGN_HINTS) else "literal/runtime"
                uses_loc=any(h in ctx for h in LOC_HINTS)
                modrows.append((str(p.relative_to(base)),i+1,method_of(lines,i),kind,uses_loc,raw[:300]))
    # compact duplicate literals
    seen=set(); compact=[]
    for r in modrows:
        key=(r[2],r[5])
        if key in seen: continue
        seen.add(key); compact.append(r)
    rows.append((wid,modid,asm,len(files),loc_calls,compact))
out=[]
out.append("# Probably Stolen localization path audit\n")
out.append("Generated by GitHub Actions from decompiled third-party DLLs. Analysis only; no third-party binary is modified.\n")
for wid,modid,asm,nfiles,loc_calls,items in rows:
    out.append(f"## {modid} ({wid})\n")
    out.append(f"- Assembly: \`{asm}.dll\`")
    out.append(f"- Decompiled C# files: {nfiles}")
    out.append(f"- Source lines mentioning localization APIs/helpers: {loc_calls}")
    direct=sum(1 for x in items if x[3]=="direct/display assignment" and not x[4])
    out.append(f"- Candidate direct user-visible assignments without nearby localization call: **{direct}**")
    out.append("")
    out.append("|file:line|method/context|class|near localization|literal|")
    out.append("|---|---|---|---:|---|")
    for f,ln,meth,kind,uses,lit in items[:350]:
        lit=lit.replace("|","\\|").replace("\n","\\n")
        meth=meth.replace("|","\\|")
        out.append(f"|\`{f}:{ln}\`|{meth}|{kind}|{'yes' if uses else 'no'}|{lit}|")
    out.append("")
OUT.parent.mkdir(parents=True,exist_ok=True)
OUT.write_text("\n".join(out),encoding="utf-8")
print(f"wrote {OUT}")
